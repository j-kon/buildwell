'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=(rel)=>fs.readFileSync(path.join(root,rel),'utf8');
const manifest=JSON.parse(read('public/manifest.webmanifest'));
const config=JSON.parse(read('vercel.json'));
const script=read('public/demo-api.js');
assert.equal(manifest.display,'standalone');
assert.ok(manifest.icons.find(x=>x.sizes==='192x192'));
assert.ok(manifest.icons.find(x=>x.sizes==='512x512'&&x.purpose==='maskable'));
for(const asset of manifest.icons)assert.ok(fs.existsSync(path.join(root,'public',asset.src)),asset.src);
assert.equal(config.outputDirectory,'public');
assert.equal(config.framework,null);
assert.ok(read('public/index.html').includes('manifest.webmanifest'));
assert.ok(read('public/index.html').includes('/demo-api.js'));
assert.ok(read('public/mobile.css').includes('.mobile-tabbar'));
assert.ok(read('public/install.js').includes('beforeinstallprompt'));
assert.ok(read('public/sw.js').includes("addEventListener('fetch'"));
for(const part of ['auth/login','auth/register','/requests','demo-pay','progress','quote','assign','/artisans']) assert.ok(script.includes(part),part);
for(const f of ['public/vendor/react.min.js','public/vendor/react-dom.min.js','public/app.js','public/styles.css','public/mobile.css','public/manifest.webmanifest','public/sw.js','public/install.js'])assert.ok(fs.statSync(path.join(root,f)).size>0,f);
console.log('PASS: React asset bundle, core demo routes, mobile styling, installability, manifest, icons and Vercel output.');
